#!/usr/bin/env python3
"""Replay the deterministic checks on every golden case, as a live run with its as_of will see them.

Each case gets the upstream files the agent reads at its upstream_commit, the posted title and body with the
form's labels, and the corpus cut at as_of (plus corpus_extra), then runs triage_checks.py on them. The table
shows the facts the agent will start from and, for each issue number an expected comment must cite and each
planted issue, its rank in the duplicate search (the agent sees the top 5). It replays the scripts, not the
agent, so it shows which expected outcomes the facts allow, not what the agent will decide.
Writes evals/golden/replay.md.
Usage: python3 evals/golden/replay_checks.py UPSTREAM   (the clone build_cases.py uses)
"""
import contextlib
import gzip
import io
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / ".claude/skills/issue-triage/scripts"))
import triage_checks as tc  # noqa: E402
from build_cases import UPSTREAM_PATHS  # noqa: E402
from prepare_context import corpus_as_of, when  # noqa: E402

SANDBOX = "wzinl/cs467-as3-triage-agent"


def checkout(up, sha, root):
    """The files the checks read, as they were at sha: small paths in full, resource docs by name only."""
    def git(*a):
        return subprocess.run(["git", "-C", up, *a], check=True, capture_output=True).stdout
    for p in UPSTREAM_PATHS:
        if p.startswith("website/docs/"):
            continue
        for f in git("ls-tree", "-r", "--name-only", sha, "--", p).decode().split():
            (root / f).parent.mkdir(parents=True, exist_ok=True)
            (root / f).write_bytes(git("show", f"{sha}:{f}"))
    names = sorted(prefix + "aws_" + os.path.basename(f).split(".")[0]
                   for kind, prefix in (("r", ""), ("d", "data."))
                   for f in git("ls-tree", "--name-only", sha, f"website/docs/{kind}/").decode().split()
                   if f.endswith(".html.markdown"))
    (root / "resources.txt").write_text("\n".join(names) + "\n")


def replay(case_dir, corpus, roots, up, tmp):
    inp, exp = (json.loads((case_dir / f).read_text()) for f in ("input.json", "expected.json"))
    root = roots.get(inp["upstream_commit"])
    if root is None:
        root = roots[inp["upstream_commit"]] = tmp / inp["upstream_commit"]
        checkout(up, inp["upstream_commit"], root)
    work = tmp / "case"
    work.mkdir(exist_ok=True)
    (work / "resources.txt").write_text((root / "resources.txt").read_text())
    (work / "issue.json").write_text(json.dumps({
        "number": 1, "url": f"https://github.com/{SANDBOX}/issues/1", "repo": SANDBOX,
        "title": inp["posted"]["title"], "body": inp["posted"]["body"], "author": "reporter",
        "author_association": inp["issue"]["author_association"], "labels": inp["issue"]["form_labels"],
        "created_at": inp["as_of"], "as_of": inp["as_of"]}))
    (work / "corpus.json").write_text(json.dumps({"issues": corpus_as_of(corpus + inp["corpus_extra"], when(inp["as_of"]))}))
    tc.TRIAGE_DIR, tc.REPO, tc.TOP_K = str(work), str(root), 10 ** 6   # every candidate, to rank the ones that matter
    with contextlib.redirect_stdout(io.StringIO()):
        tc.main()
    c = json.loads((work / "checks.json").read_text())
    ranked = [s["number"] for s in c["similar_issues"]]
    wanted = [int(p) for p in exp["comment"].get("must_include_any", []) if re.fullmatch(r"\d+", p)]
    wanted += [x["number"] for x in inp["corpus_extra"]]
    v, s = c["versions"], c["services"]
    return {"id": exp["id"], "expected": " or ".join(exp["decision"]),
            "missing": ", ".join(c["form"]["missing_required"]) or "-",
            "provider": f"{v['provider'] or '?'} ({v['provider_status']})",
            "fixes": ", ".join(v["newer_fixes"]) or "-",
            "service": f"{s['primary_service_label'] or '-'}{'' if s['primary_service_label'] in s['regex_labeler_would_apply'] else ' (not by labeler)' if s['primary_service_label'] else ''}",
            "top": ", ".join(f"{x['number']} {x['band']} {x['score']}" for x in c["similar_issues"][:5]) or "-",
            "rank": ", ".join(f"{n}: {ranked.index(n) + 1 if n in ranked else 'absent'}"
                              + (f" ({c['similar_issues'][ranked.index(n)]['score']})" if n in ranked else "") for n in wanted) or "-"}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    corpus = json.load(gzip.open(ROOT / "evals/data/corpus.json.gz"))
    out = ["# Check replay", "", "Generated by `evals/golden/replay_checks.py`; do not edit. What triage_checks.py reports for "
           "each case as its live run will see it. `cited ranks` gives each issue number the expected comment must cite, "
           "and each planted issue, with its rank among all candidates (the agent sees the top 5) and its score.", ""]
    roots = {}
    with tempfile.TemporaryDirectory() as tmp:
        for group in ("held-out", "dev"):
            rows = [replay(d, corpus, roots, sys.argv[1], Path(tmp)) for d in sorted((HERE / "cases" / group).iterdir())]
            out += [f"## {group}", "", "| case | expected | form fields missing | provider | newer fixes | primary service | "
                    "top 5 similar | cited ranks |", "|---|---|---|---|---|---|---|---|"]
            out += ["| " + " | ".join(r.values()) + " |" for r in rows] + [""]
    (HERE / "replay.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
